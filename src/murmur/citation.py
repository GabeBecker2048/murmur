"""How to cite Murmur: one source for ``CITATION.cff`` (written by scripts/gen_docs.py),
``GET /api/v1/citation`` and the dashboard's Cite button.

Authors are the project's three contributors (as listed in the README).
"""

from __future__ import annotations

REPOSITORY = "https://github.com/GabeBecker2048/murmur"
TITLE = "Murmur: news-headline sentiment and stock returns for the largest US companies"
AUTHORS: tuple[dict[str, str], ...] = (
    {"given-names": "Gabe", "family-names": "Becker", "alias": "GabeBecker2048"},
    {"given-names": "Wyatt", "family-names": "Burch-Celentano", "alias": "wyatthbc"},
    {"given-names": "Sam", "family-names": "Chapoton", "alias": "samchapoton"},
)
ABSTRACT = (
    "A daily dataset and pipeline: FinBERT sentiment of news headlines for the 100 largest "
    "US-listed companies, their daily returns, and the correlation between the two at a "
    "one-session lead and lag, with a cap-weighted index (the Murmur 100) and frozen "
    "findings snapshots."
)
KEYWORDS = ("sentiment analysis", "financial news", "stock returns", "FinBERT", "dataset")


def _names() -> list[str]:
    out = []
    for a in AUTHORS:
        if a.get("family-names"):
            out.append(f"{a['family-names']}, {a.get('given-names', '')}".strip(", "))
        else:
            out.append(a.get("name") or a["alias"])
    return out


def _apa_names() -> str:
    """APA style: "Becker, G., Burch-Celentano, W., & Chapoton, S."."""
    names = [
        f"{a['family-names']}, {a['given-names'][0]}." if a.get("family-names") else a["alias"]
        for a in AUTHORS
    ]
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + ", & " + names[-1]


def _year(day: str | None) -> str:
    return (day or "2026")[:4]


def cff(version: str, data_version: str, released: str | None = None) -> str:
    lines = [
        "# Generated by scripts/gen_docs.py from src/murmur/citation.py; edit that, not this.",
        "cff-version: 1.2.0",
        'message: "If you use Murmur or its data, please cite it as below."',
        "type: software",
        f'title: "{TITLE}"',
        "authors:",
    ]
    for a in AUTHORS:
        first = True
        for key in ("family-names", "given-names", "name", "alias"):
            if key in a:
                lines.append(f'  {"- " if first else "  "}{key}: "{a[key]}"')
                first = False
    lines += [
        f'version: "{version}"',
        f'repository-code: "{REPOSITORY}"',
        "license: MIT",
        f'abstract: "{ABSTRACT}"',
        "keywords:",
        *[f'  - "{k}"' for k in KEYWORDS],
        "references:",
        "  - type: data",
        f'    title: "Murmur data (data version {data_version})"',
        "    authors:",
        *[
            line
            for a in AUTHORS
            for line in (
                f'      - family-names: "{a["family-names"]}"',
                f'        given-names: "{a["given-names"]}"',
            )
        ],
        '    license: "CC-BY-4.0"',
        f'    url: "{REPOSITORY}"',
        f'    version: "{data_version}"',
    ]
    if released:
        lines.insert(lines.index(f'version: "{version}"') + 1, f'date-released: "{released}"')
    return "\n".join(lines) + "\n"


def bibtex(version: str, data_version: str, findings: dict | None = None, url: str = "") -> str:
    authors = " and ".join(_names())
    if findings:
        fid = findings["id"]
        title = (findings.get("text") or {}).get("title") or fid
        end = findings["window"]["end"]
        return (
            f"@misc{{murmur_findings_{fid.replace('-', '_')},\n"
            f"  author = {{{authors}}},\n"
            f"  title = {{Murmur findings {fid}: {title}}},\n"
            f"  year = {{{_year(end)}}},\n"
            f"  note = {{Sessions {findings['window']['start']} to {end}; "
            f"data version {data_version}; CC BY 4.0}},\n"
            f"  url = {{{url or REPOSITORY}}}\n"
            "}\n"
        )
    return (
        "@misc{murmur,\n"
        f"  author = {{{authors}}},\n"
        f"  title = {{{TITLE}}},\n"
        "  year = {2026},\n"
        f"  note = {{Software version {version}, data version {data_version}; "
        "code MIT, data CC BY 4.0}},\n"
        f"  url = {{{url or REPOSITORY}}}\n"
        "}\n"
    )


def apa(version: str, data_version: str, findings: dict | None = None, url: str = "") -> str:
    authors = _apa_names()
    if findings:
        title = (findings.get("text") or {}).get("title") or findings["id"]
        end = findings["window"]["end"]
        return (
            f"{authors} ({_year(end)}). Murmur findings {findings['id']}: {title} "
            f"[Data set, version {data_version}]. {url or REPOSITORY}"
        )
    return (
        f"{authors} (2026). {TITLE} (Version {version}) [Computer software and data set, "
        f"data version {data_version}]. {url or REPOSITORY}"
    )
