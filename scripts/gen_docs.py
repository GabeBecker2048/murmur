"""Write the generated reference pages under docs/: configuration, API, data dictionary.

    uv run python scripts/gen_docs.py           # rewrite docs/*.md
    uv run python scripts/gen_docs.py --check   # exit 1 if any page is stale (CI)

Everything comes from the code (SETTINGS_SCHEMA and the packaged defaults, the FastAPI
OpenAPI document, the dataset registry and murmur.dictionary), so the pages cannot drift.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
HEADER = "<!-- Generated by scripts/gen_docs.py; edit the code, not this file. -->\n\n"


def _cell(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def _default(raw: dict, path: str):
    node = raw
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def configuration() -> str:
    from murmur import config as c
    from murmur.logs import ENV_LOG_FORMAT

    raw = c.packaged_defaults()
    lines = [
        HEADER + "# Configuration\n",
        "Resolution: `--config PATH` > `MURMUR_CONFIG` > `./murmur.toml` > the packaged "
        "defaults, then the API-edited `<data_dir>/settings.toml` over that, then the "
        "environment. Every table merges key by key except `[universe.static]`, which "
        "a user file replaces wholesale.\n",
        "## Settings\n",
        "Editable from the admin page unless marked locked.\n",
        "| Key | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for entry in c.SETTINGS_SCHEMA:
        path = entry["path"]
        kind = entry["type"]
        if entry.get("choices"):
            kind += " (" + ", ".join(str(x) for x in entry["choices"]) + ")"
        default = _default(raw, path)
        if isinstance(default, dict):
            default = f"{len(default)} entries"
        elif default is not None:
            default = json.dumps(default)
        help_text = entry.get("help", "")
        if path in c.LOCKED_KEYS:
            help_text += " Locked: not editable from the API."
        lines.append(f"| `{path}` | {_cell(kind)} | {_cell(default)} | {_cell(help_text)} |")
    lines += [
        "",
        "Locked keys (file or environment only): "
        + ", ".join(f"`{k}`" for k in c.LOCKED_KEYS)
        + ".\n",
        "## Environment\n",
        "| Variable | Purpose |",
        "|---|---|",
        f"| `{c.ENV_CONFIG}` | Path of the ops config file. |",
        f"| `{c.ENV_DATA_DIR}` | The data directory (store, published files, settings). |",
        f"| `{c.ENV_API_TOKEN}` | Bearer token for POST/PUT/DELETE; writes are refused "
        "without it. |",
        f"| `{c.ENV_FINNHUB_KEY}` | Finnhub API key (news source `finnhub`). |",
        f"| `{c.ENV_POLYGON_KEY}` | Polygon API key (prices, splits). |",
        f"| `{c.ENV_CORS}` | Comma-separated origins allowed to call the API from a browser. |",
        f"| `{ENV_LOG_FORMAT}` | `json` for one JSON object per log line. |",
        "| `MURMUR_S3_BUCKET`, `MURMUR_S3_REGION`, `MURMUR_S3_ENDPOINT` | The offsite backup "
        "target, read by the backup service only (`murmur offsite`). |",
        "| `AWS_ACCESS_KEY_ID`, `AWS_SECRET_ACCESS_KEY` | Its credentials (boto3). |",
        "",
    ]
    return "\n".join(lines)


def api() -> str:
    from murmur.api.app import create_app
    from murmur.config import ConfigProvider

    with tempfile.TemporaryDirectory() as tmp:
        ops = Path(tmp) / "murmur.toml"
        ops.write_text(
            f'data_dir = "{Path(tmp) / "data"}"\n'
            '[universe]\nsource = "static"\n[universe.static]\nAAPL = "Apple"\n'
        )
        spec = create_app(ConfigProvider(ops, env={}), run_worker=False).openapi()
    lines = [
        HEADER + "# API\n",
        "Base path `/api/v1`. Reads are open; POST, PUT and DELETE need "
        '`Authorization: Bearer $MURMUR_API_TOKEN`. Errors are `{"detail": ...}`; lists '
        "take `limit`/`offset` and return `total`. The interactive version is `/docs` on a "
        "running instance; published files are under `/data` (see the data dictionary).\n",
    ]
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, ops_ in sorted(spec["paths"].items()):
        for method, op in ops_.items():
            tag = (op.get("tags") or ["other"])[0]
            by_tag.setdefault(tag, []).append((method.upper(), path, op))
    for tag in sorted(by_tag):
        lines.append(f"## {tag}\n")
        for method, path, op in by_tag[tag]:
            lines.append(f"### `{method} {path}`\n")
            doc = (op.get("description") or op.get("summary") or "").strip()
            if doc:
                lines.append(" ".join(doc.split()) + "\n")
            params = [p for p in op.get("parameters", []) if p.get("in") in ("query", "path")]
            if params:
                lines.append("| Parameter | In | Type | Default |")
                lines.append("|---|---|---|---|")
                for p in params:
                    schema = p.get("schema", {})
                    kind = schema.get("type") or " or ".join(
                        x.get("type", "") for x in schema.get("anyOf", []) if x.get("type")
                    )
                    default = schema.get("default")
                    lines.append(
                        f"| `{p['name']}` | {p['in']} | {_cell(kind)} | "
                        f"{_cell('' if default is None else json.dumps(default))} |"
                    )
                lines.append("")
    return "\n".join(lines)


def data_dictionary() -> str:
    from murmur.config import load_config
    from murmur.dictionary import describe
    from murmur.export import datasets, table_cadence

    with tempfile.TemporaryDirectory() as tmp:
        user = Path(tmp) / "c.toml"
        user.write_text('[universe]\nsource = "static"\n[universe.static]\nAAPL = "Apple"\n')
        config = load_config(user, env={})
    lines = [
        HEADER + "# Data dictionary\n",
        "Murmur publishes Parquet files under `/data`, organised by dataset:\n",
        "```",
        "{dataset}/{YYYY}/{MM}/{DD}/{YYYYMMDD}.{table}.parquet   daily tables",
        "{dataset}/{YYYY}/{MM}/{YYYYMM}.{table}.parquet          monthly tables, and daily",
        "                                                        tables of a finished month",
        "```\n",
        "`/data/index.json` lists every file with its rows, size and date. Add "
        "`?format=csv` to any `.parquet` URL for CSV. Every file carries its license in "
        "the Parquet footer metadata (`license`, `notice`, `attribution`, `contact`), and "
        "`/data` responses repeat it as `Link` and `X-Murmur-*` headers. A table with no "
        "rows for a period has no file.\n",
        "Each footer also records `murmur_data_version`, the version of the published "
        "data (see [stability.md](stability.md) and [data-changelog.md](data-changelog.md)), "
        "`murmur_version` (the software that wrote it) and `murmur_period`. Frozen findings "
        "snapshots are JSON files at `findings/<id>.json`, the newest also at "
        "`findings/latest.json`.\n",
    ]
    for ds in datasets(config):
        license_name = ds.license.get("name", "")
        lines += [
            f"## `{ds.name}`: {ds.title}\n",
            " ".join(ds.description.split()) + "\n",
            f"License: **{license_name}**. Dataset cadence: {ds.cadence}.\n",
        ]
        for t in ds.tables:
            lines += [
                f"### `{t.name}` ({table_cadence(ds, t)})\n",
                "Key: " + ", ".join(f"`{k}`" for k in t.key) + ".\n",
                "| Column | Description |",
                "|---|---|",
            ]
            lines += [f"| `{c}` | {_cell(describe(t.name, c))} |" for c in t.columns]
            lines.append("")
    return "\n".join(lines)


PAGES = {
    "configuration.md": configuration,
    "api.md": api,
    "data-dictionary.md": data_dictionary,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, build in PAGES.items():
        text = build().rstrip() + "\n"
        path = DOCS / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            DOCS.mkdir(exist_ok=True)
            path.write_text(text)
            print(f"wrote docs/{name}")
    if stale:
        print(
            "stale: "
            + ", ".join(f"docs/{n}" for n in stale)
            + " (run: uv run python scripts/gen_docs.py)",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
